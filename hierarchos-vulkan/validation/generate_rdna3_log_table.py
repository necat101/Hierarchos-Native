"""Generate mathematical FP32 split-log tables; no oracle/model data as input."""
import math,struct
from pathlib import Path
def bits(x):return struct.unpack('<I',struct.pack('<f',x))[0]
def value(x):return struct.unpack('<f',struct.pack('<I',x))[0]
def generate():
    tables=[[],[],[]]
    for i in range(129):
        logarithm=math.log1p(i/128.)
        lead=bits(logarithm)&0xfffff000
        remainder=logarithm-value(lead)
        tail=bits(remainder)
        if value(tail)>remainder:tail-=1
        for table,item in zip(tables,[bits(2./(1.+i/128.)),lead,tail]):table.append(item)
    out=['// Generated by validation/generate_rdna3_log_table.py; mathematical constants.',
         '// Positive-normal Windows CRT logf schedule used by CPU flash SDPA.']
    for name,table in zip(['inverse','lead','tail'],tables):
        out.append('const uint rdna3_log_'+name+'[129]=uint[129](\n'+',\n'.join(
            '    '+','.join(f'0x{x:08x}u' for x in table[i:i+8]) for i in range(0,len(table),8))+');')
    out.append('''float rdna3_scalar_logf(float d) {
    precise float delta=d-1.0;
    if(abs(delta)<0.0625) {
        precise float denom=2.0+delta;
        precise float q=fp32_div(delta,denom);
        precise float correction=delta*q;
        precise float t=q+q;
        precise float square=t*t;
        precise float cube=t*square;
        float p=fma(0.012500000186264515,square,0.0833333358168602);
        precise float rest=fma(cube,p,-correction);
        return delta+rest;
    }
    uint bits=floatBitsToUint(d),mantissa=bits&0x7fffffu;
    float exponent=float(int(bits>>23u)-127);
    uint index=(mantissa+0x8000u)>>16u;
    float y=uintBitsToFloat(mantissa|0x3f000000u);
    float center=uintBitsToFloat((index<<16u)|0x3f000000u);
    precise float diff=center-y;
    precise float r=diff*uintBitsToFloat(rdna3_log_inverse[index]);
    float p=fma(r,0.3333333432674408,0.5);
    precise float square=r*r;
    float polynomial=fma(p,square,r);
    precise float low=fma(exponent,uintBitsToFloat(0x3805fdf4u),-polynomial);
    precise float high=fma(exponent,0.693115234375,uintBitsToFloat(rdna3_log_lead[index]));
    precise float rest=low+uintBitsToFloat(rdna3_log_tail[index]);
    return high+rest;
}''')
    return '\n'.join(out)+'\n'
if __name__=='__main__':Path('shaders/fp32_scalar_log_rdna3.glsl').write_text(generate(),newline='\n')
