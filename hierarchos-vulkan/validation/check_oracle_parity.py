"""Compare this tree's shaders against the read-only stable oracle tree.

The stable tree at `..\\Hierarchos-Native-stable\\Hierarchos-Native` is the
pre-optimization baseline: it carries the AVX512/RDNA3 work and predates the Gen9
and lane-2 sweeps. Its modules are the validated shipping bytes, so a portable
artifact that drifts from it is a regression even when the drift is "only"
codegen. That has already happened once: `parameter_matmul_weight_grad.spv` was
regenerated by a newer `glslc`, which outlined a helper the oracle inlined, and
the difference was 404 bytes of different instruction scheduling.

This script never writes to the oracle. It opens its files for reading only, and
the local side is only read as well -- it reports, it does not repair.

The comparison covers every shader source and artifact present in both trees,
normalizing `\\r\\n` so a checkout's line endings are not drift. Files that exist
only here are informational: the vendor modules and the pre-tuning scalar
fallbacks were added after the oracle. A drift is a *shared* file whose bytes
differ, or an oracle file that is now missing.

Deliberate divergences live in `validation/oracle_divergences.json`, one entry per
path with the reason and who owns the decision. An entry only silences a
divergence that exists; if the file matches the oracle again the entry is stale
and fails, so the list cannot rot into blanket permission.

An entry is `"state": "modified"` (the default) or `"state": "removed"`, because
retiring a kernel is a legitimate oracle difference too: its source and artifacts
are present in the baseline and deliberately absent here. A `modified` entry is
stale when the file matches again; a `removed` entry is stale when the file comes
back. Neither kind can silence the other.

Exit codes:

    0  every shared shader matches the oracle, or diverges only where listed
    1  at least one unexplained drift, a missing oracle file, or a stale entry
    2  the oracle tree is not available (a skip, not a pass)

Run from `hierarchos-vulkan/`:

    python validation/check_oracle_parity.py
    python validation/check_oracle_parity.py --oracle ..\\Hierarchos-Native-stable\\Hierarchos-Native
    python validation/check_oracle_parity.py --json
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIVERGENCES = ROOT / "validation" / "oracle_divergences.json"
ENV_ORACLE = "HIERARCHOS_STABLE_ORACLE"
ORACLE_DIR_NAME = Path("Hierarchos-Native-stable") / "Hierarchos-Native"


def default_oracle() -> Path:
    """The first `Hierarchos-Native-stable/Hierarchos-Native` beside a parent.

    The crate sits one level below the repository root, which itself sits beside
    the oracle checkout, so the default is resolved by walking up rather than by a
    fixed number of `..`, which breaks as soon as the tree is nested differently.
    """
    for ancestor in ROOT.parents:
        candidate = ancestor / ORACLE_DIR_NAME
        if candidate.is_dir():
            return candidate
    return ROOT.parent / ORACLE_DIR_NAME

TEXT_SUFFIXES = {".comp", ".glsl", ".vert", ".frag", ".md", ".txt"}

# Modules the tuning work is allowed to own. The oracle predates them, so a
# difference here is the point of the vendor layer rather than drift; the vendor
# layer's own tests (bit-exactness against the portable kernel, selection,
# capability gates) are what qualify them. Everything else is portable and must
# match the oracle.
VENDOR_SUFFIXES = (
    "_intel_gen9.comp",
    "_intel_gen9.spv",
    "_amd_rdna3.comp",
    "_amd_rdna3.spv",
)
VENDOR_DIRS = ("vendor_experiments/", "portable_scalar/")


def is_vendor(name: str) -> bool:
    return name.startswith(VENDOR_DIRS) or name.endswith(VENDOR_SUFFIXES)

EXIT_OK = 0
EXIT_DRIFT = 1
EXIT_UNAVAILABLE = 2


def shader_dir(tree: Path) -> Path | None:
    """The `shaders/` directory inside a checkout, crate, or repository root."""
    for candidate in (tree / "shaders", tree / "hierarchos-vulkan" / "shaders"):
        if candidate.is_dir():
            return candidate
    return None


def normalize(path: Path) -> bytes:
    """Bytes with line endings normalized, so a checkout's CRLF is not drift."""
    data = path.read_bytes()
    if path.suffix.lower() in TEXT_SUFFIXES:
        return data.replace(b"\r\n", b"\n")
    return data


def digest(path: Path) -> str:
    return hashlib.sha256(normalize(path)).hexdigest()


DIVERGENCE_KINDS = ("modified", "removed")


def read_divergences(path: Path) -> dict[str, tuple[str, str]]:
    """Map each documented path to (reason, state)."""
    if not path.is_file():
        return {}
    document = json.loads(path.read_text(encoding="utf-8"))
    divergences = {}
    for entry in document.get("divergences", []):
        if "path" not in entry:
            continue
        state = entry.get("state", "modified")
        if state not in DIVERGENCE_KINDS:
            raise SystemExit(
                f"FAIL {entry['path']}: unknown divergence state {state!r}; "
                f"expected one of {', '.join(DIVERGENCE_KINDS)}"
            )
        divergences[entry["path"].replace("\\", "/")] = (entry.get("reason", ""), state)
    return divergences


def compare(local: Path, oracle: Path) -> dict:
    """Compare the two shader trees, classifying every shared file."""
    local_files = {p.relative_to(local).as_posix(): p for p in local.rglob("*") if p.is_file()}
    oracle_files = {p.relative_to(oracle).as_posix(): p for p in oracle.rglob("*") if p.is_file()}
    shared = sorted(set(local_files) & set(oracle_files))
    portable = [name for name in shared if not is_vendor(name)]
    modified = [name for name in portable if digest(local_files[name]) != digest(oracle_files[name])]
    missing = [name for name in sorted(set(oracle_files) - set(local_files)) if not is_vendor(name)]
    added = sorted(set(local_files) - set(oracle_files))
    return {
        "shared": len(portable),
        "vendor_shared": len(shared) - len(portable),
        "modified": modified,
        "missing": missing,
        "added": added,
        "local": local_files,
        "oracle": oracle_files,
    }


def evaluate(report: dict, divergences: dict[str, tuple[str, str]]) -> list[str]:
    """Turn a comparison into problems, applying the documented divergences.

    A divergence is only accepted for a file that actually differs in the way its
    entry names, and only for a shared file: a `modified` entry whose file now
    matches, or a `removed` entry whose file came back, is a stale entry rather
    than permission.
    """
    modified = set(report["modified"])
    missing = set(report["missing"])
    problems = []
    for name in report["modified"]:
        documented = divergences.get(name)
        if documented is None or documented[1] != "modified":
            problems.append(
                f"{name}: differs from the oracle (local {digest(report['local'][name])[:16]}, "
                f"oracle {digest(report['oracle'][name])[:16]})"
            )
    for name in report["missing"]:
        documented = divergences.get(name)
        if documented is None or documented[1] != "removed":
            problems.append(f"{name}: present in the oracle, missing here")
    for name, (_, state) in sorted(divergences.items()):
        if state == "modified" and name not in modified:
            problems.append(
                f"{name}: listed as a deliberate divergence but does not differ from the oracle "
                f"(stale entry)"
            )
        elif state == "removed" and name not in missing:
            problems.append(
                f"{name}: listed as a deliberate removal but is not missing from this tree "
                f"(stale entry)"
            )
    return problems


def resolve_oracle(value: str | None) -> Path | None:
    candidate = value or os.environ.get(ENV_ORACLE) or str(default_oracle())
    path = Path(candidate).expanduser()
    if not path.is_absolute():
        path = (Path.cwd() / path).resolve()
    return path if shader_dir(path) is not None else None


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--oracle",
        help=f"stable checkout, crate or repository root (default: ${ENV_ORACLE} or {default_oracle()})",
    )
    parser.add_argument(
        "--local",
        type=Path,
        default=ROOT,
        help="tree to check (default: this crate)",
    )
    parser.add_argument("--divergences", type=Path, default=DIVERGENCES)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)

    local = shader_dir(args.local.expanduser())
    oracle_root = resolve_oracle(args.oracle)
    if local is None:
        print(f"FAIL no shaders/ directory under {args.local}", file=sys.stderr)
        return EXIT_DRIFT
    if oracle_root is None:
        # A missing oracle is a skip. Saying "pass" here would let a machine without
        # the baseline report parity it never checked.
        print(
            f"SKIP oracle tree not found: {args.oracle or os.environ.get(ENV_ORACLE) or default_oracle()}\n"
            f"     pass --oracle PATH or set {ENV_ORACLE} to the read-only stable checkout",
            file=sys.stderr,
        )
        return EXIT_UNAVAILABLE

    report = compare(local, shader_dir(oracle_root))
    divergences = read_divergences(args.divergences)
    problems = evaluate(report, divergences)

    if args.json:
        print(
            json.dumps(
                {
                    "shared": report["shared"],
                    "vendor_shared": report["vendor_shared"],
                    "modified": report["modified"],
                    "missing": report["missing"],
                    "added": report["added"],
                    "divergences": sorted(divergences),
                    "problems": problems,
                },
                indent=2,
            )
        )
    else:
        for problem in problems:
            print(f"FAIL {problem}")
        print(
            f"compared {report['shared']} portable shader file(s) against {shader_dir(oracle_root)}; "
            f"{len(report['modified'])} differ ({sum(1 for _, kind in divergences.values() if kind == 'modified')} documented), "
            f"{len(report['missing'])} missing ({sum(1 for _, kind in divergences.values() if kind == 'removed')} retired), "
            f"{len(report['added'])} only here, "
            f"{report['vendor_shared']} vendor file(s) excluded"
        )
    if problems:
        print(f"FAIL: {len(problems)} shader artifact(s) drift from the stable oracle")
        return EXIT_DRIFT
    print("PASS: every shared shader matches the stable oracle")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
